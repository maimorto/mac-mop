import Foundation

// ClickFix clipboard guard: decides whether text the user just copied is an
// infostealer command they are being talked into pasting into Terminal.
//
// Idea from ClickGrab (a collection of ClickFix lure pages): the attack is a
// web page that puts `curl … | bash` or `echo <base64> | base64 -d | sh` on
// the clipboard and tells the user to paste it. Warning at copy time beats
// finding the stealer afterwards.
//
// Pure policy, no AppKit: the menu bar helper feeds it the pasteboard types
// and the string. Clipboard text is never logged or stored; only the
// verdict (rule + severity) leaves this file.

public struct ClipboardThreatVerdict: Sendable, Equatable {
    /// Strongest `.high` finding.
    public let rule: ThreatRule
    /// Every `.high` rule that matched, strongest first.
    public let rules: [ThreatRule]
}

public enum ClipboardThreatPolicy {
    /// Shared defaults key (`SharedAppState.defaults`), default on.
    public static let enabledKey = "clipboardGuardEnabled"
    /// Poll interval: checking `changeCount` is a cheap integer read.
    public static let pollInterval: TimeInterval = 0.7
    /// Real ClickFix commands are short; long text is prose or code to read.
    public static let maxTextBytes = 64 * 1024
    static let minTextLength = 8

    public static func isEnabled(_ defaults: UserDefaults) -> Bool {
        defaults.object(forKey: enabledKey) as? Bool ?? true
    }

    /// Pasteboard types that mark content as secret or transient
    /// (nspasteboard.org conventions, used by password managers).
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    /// Password managers: anything they put on the clipboard is skipped,
    /// even without a concealed marker.
    public static let passwordManagerBundleIDs: Set<String> = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "com.dashlane.Dashlane",
        "com.dashlane.dashlanephonefinal",
        "com.lastpass.LastPass",
        "com.enpass.Enpass",
        "me.proton.pass.electron",
        "com.nordpass.macos.NordPass",
        "com.keepersecurity.passwordmanager",
        "net.antelle.keeweb",
        "in.sinew.Enpass-Desktop",
        "com.strongbox.mac",
    ]

    /// `org.nspasteboard.source` carries the bundle id of the app that copied.
    public static let sourceType = "org.nspasteboard.source"

    /// Whether the text may be read at all. `source` is the copying app's
    /// bundle id when known (pasteboard source marker or frontmost app).
    public static func shouldInspect(types: [String], source: String?) -> Bool {
        guard types.contains(where: { $0 == "public.utf8-plain-text" || $0 == "NSStringPboardType" }) else { return false }
        if types.contains(where: ignoredTypes.contains) { return false }
        if let source, passwordManagerBundleIDs.contains(source) { return false }
        return true
    }

    /// Cheap gate before the analyzer: short enough, and mentions something a
    /// shell / osascript one-liner would.
    public static func looksLikeCommand(_ text: String) -> Bool {
        let bytes = text.utf8.count
        guard bytes >= minTextLength, bytes <= maxTextBytes else { return false }
        let lower = text.lowercased()
        return commandMarkers.contains { lower.contains($0) }
    }

    static let commandMarkers = [
        "curl", "wget", "bash", "zsh", "sh -c", "| sh", "|sh", "osascript", "base64", "eval", "chmod", "xattr",
        "/bin/", "$(", "`", "echo ", "printf", "python", "perl", "nohup", "dscl", "security ", "ditto", "xxd",
        "/tmp/", "open -a", "launchctl",
    ]

    /// A verdict when the text contains at least one `.high` behaviour
    /// (`ThreatCommandAnalyzer`); `.medium` findings (e.g. a Homebrew
    /// install one-liner from its official URL) never warn.
    public static func evaluate(_ text: String) -> ClipboardThreatVerdict? {
        guard looksLikeCommand(text) else { return nil }
        let high = ThreatCommandAnalyzer.analyze(text)
            .filter { $0.severity == .high }
            .map(\.rule)
        guard let first = high.first else { return nil }
        let ordered = [first] + high.dropFirst().filter { $0 != first }
        return ClipboardThreatVerdict(rule: first, rules: ordered)
    }

    /// Full decision for one pasteboard change.
    public static func verdict(types: [String], source: String?, text: () -> String?) -> ClipboardThreatVerdict? {
        guard shouldInspect(types: types, source: source), let text = text() else { return nil }
        return evaluate(text)
    }

    // MARK: Strings

    public static var warningTitle: String {
        UIText.t("Non incollarlo nel Terminale", "Don't paste it into Terminal")
    }

    public static var warningBody: String {
        UIText.t("Il comando che hai copiato è usato dagli infostealer: non incollarlo nel Terminale.",
                 "The command you copied is used by infostealers: don't paste it into Terminal.")
    }

    public static var warningDetail: String {
        UIText.t("Siti falsi (\"verifica di non essere un robot\", \"correggi l'errore\") chiedono di incollare comandi come questo per installare malware che ruba password e wallet.",
                 "Fake sites (\"verify you are human\", \"fix the error\") ask you to paste commands like this to install malware that steals passwords and wallets.")
    }

    public static var clearAction: String { UIText.t("Svuota appunti", "Clear Clipboard") }
    public static var ignoreAction: String { UIText.t("Ignora", "Ignore") }
}
